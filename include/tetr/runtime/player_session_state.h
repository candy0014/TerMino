namespace Runtime {

struct QueuedPiece {
    Piece::Type type = Piece::Type::none();
    bool startsNewBag = false;

    friend bool operator==(const QueuedPiece& lhs, const QueuedPiece& rhs) noexcept {
        return lhs.type == rhs.type && lhs.startsNewBag == rhs.startsNewBag;
    }
};

struct PieceQueueState {
    std::deque<QueuedPiece> bag;
    std::vector<Piece::Type> nextPreview;
    std::vector<Piece::Type> allowedPieces;
    int bagCount = 0;
    std::vector<int> foolLastTypes;
    bool qpBagBreather = true;
    std::mt19937 random;
    std::optional<TetrioRandom> tetrioRandom;
    BagRandomizerState randomizerState;
};


struct GarbageRiseState {
    // Armed by an entry trigger. Rows stay in the cancellable buffer until
    // they actually rise, but need no further lock or buffer delay.
    int remainingLines=0;
    std::optional<TimePoint> nextRow;
    Duration interval{};
    void clear() { remainingLines=0; nextRow.reset(); interval={}; }
};

struct GarbageSessionState {
    int previousHoleColumn=-1;
    GarbageHolePattern holePattern{};
    bool chessboardParity = false;
    std::vector<int> holeOrder;
    std::deque<GarbagePacket> buffer;
    GarbageRiseState rising;
    double incomingFraction = 0.0;
    GarbageCancellationState cancellation;
    std::mt19937 random;
    std::optional<TetrioGarbageRandom> tetrioRandom;
};

struct PendingAttack {
    MultiplayerSequenceId sequenceId{};
    int attack = 0;
    int targetSlot = -1;

    friend bool operator==(const PendingAttack& lhs, const PendingAttack& rhs) noexcept {
        return lhs.sequenceId == rhs.sequenceId && lhs.attack == rhs.attack;
    }
};

struct MultiplayerSessionState {
    std::deque<PendingAttack> pendingSends;
    MultiplayerSequenceId sendId{};
    MultiplayerSequenceId receiveId{};
    int lastDamageSource = -1;
};

struct PlayerTimingState {
    TimePoint timedGarbage{};
    TimePoint frameUpdate{};
    TimePoint framePoll{}; // Wall time: keep UI and network responsive while frozen.
    TimePoint autoplay{};
    TimePoint qpGravity{};
    TimePoint multiplayerSync{};
    std::optional<TimePoint> entryDelayEnd;
    std::optional<TimePoint> realGameStart;
    std::optional<Duration> completedGameTime;
    std::optional<Duration> completedRealTime;
    std::optional<Duration> remoteGameTime;
    std::optional<TimePoint> remoteTimeUpdated;
    double remoteTimeRate = 1.0;
    Duration remote_elapsed(TimePoint now) const {
        return remoteGameTime.value_or(Duration{})+
            (remoteTimeUpdated?std::max(Duration{},now-*remoteTimeUpdated)*remoteTimeRate:Duration{});
    }
};

// State for TETR.IO's current Clutch Clear rule.  Eligibility belongs to the
// previously locked piece and intentionally survives a Hold continuation, so
// the piece generated by Hold receives the same last-chance spawn lift.
struct ClutchSessionState {
    bool previousPieceCleared = false;
    bool currentTurnLifted = false;
    int consecutive = 0;
};

// Presentation-only accumulator for the earlier TETR.IO spike counter.  The
// timestamp uses the active game timeline (wall-clock for live play, replay
// elapsed time during playback), so replay pause and seek remain deterministic.
struct SpikeDisplayState {
    int attack = 0;
    std::optional<TimePoint> lastAttackAt;
};

struct TextDisplaySpan {
    int row = 0;
    int column = 0;
    std::size_t width = 0;
};

struct PlayerPresentationState {
    std::string username;
    // Last remote placement HUD survives the following active-piece checkpoint.
    std::uint64_t remotePlacementRevision=0;
    Piece::Type remoteSpinPiece=Piece::Type::none();
    bool remoteMini=false,remotePerfectClear=false,remoteHalfClear=false;
    int remoteClearLines=0;
    std::string roundEndHeadline;
    int margin = 0;
    int topMargin = 8;
    bool dynamicLayout = false;
    std::optional<Piece::Pose> activePose;
    std::optional<Piece::Type> activePieceType;
    // Actual piece overlay on the terminal, including full/periodic repaints.
    std::optional<Piece::Pose> paintedActivePose;
    std::optional<Piece::Type> paintedActivePieceType;
    // Actual queued type can differ from the disguised Fool NEXT preview.
    std::optional<Piece::Type> nextSpawnType;
    std::optional<Piece::Pose> nextSpawnPose; // Remote override, before Clutch/input.
    std::vector<CellPosition> spawnMarkerCells;
    std::uint64_t activePiecePaintRevision = 0;
    int blockMaxHeight = 2;
    int blockMaxWidth = 3;
    std::vector<int> garbageBufferDisplay;
    std::vector<bool> garbageBufferSegmentTops;
    bool garbageBufferDisplayDeferred = false;
    int racingGoalRows = -1;
    std::string racingGoalLabel;
    SpikeDisplayState spike;
    std::array<std::size_t, 6> messageWidths{};
    std::array<std::string, 6> messageText{};
    std::array<int,6> messageRows{{-1,-1,-1,-1,-1,-1}};
    int messageMargin=-1,messageTopMargin=-1;
    bool messageObscured=false;
    TimePoint lastMessagePaint{};
    std::array<TextDisplaySpan, 2> altitudeDisplay{};
    TextDisplaySpan undoCountDisplay{};
    std::vector<TextDisplaySpan> replayPromptDisplay;
    bool invisibleFlash = false;
    Duration visibilityTime{};
    Duration activePieceBorn{};
    bool activePieceShown=true;
    std::array<TextDisplaySpan,5> windupDisplay{};
    int windupDisplayedSegments=-1;
    int windupPulse=-1;
    double windupDisplayedStart=-1;
    int terminalColumns = 0, terminalRows = 0, layoutBoardWidth = 0, layoutBoardHeight = 0, layoutNextCount = 0;
    std::uint64_t terminalLayoutRevision = 0;
    std::uint64_t terminalPaintRevision = 0;

    int hold_panel_height() const noexcept { return blockMaxHeight + 3; }
    int next_panel_height(int nextCount) const noexcept { return (blockMaxHeight + 1) * nextCount + 3; }
};

struct PlayerSessionState {
    PlayerState gameplay;
    PieceQueueState pieces;
    GarbageSessionState garbage;
    // QUICK PLAY uses stochastic rounding for fractional attack.  Keep its
    // random stream separate so attack rolls cannot perturb piece or garbage
    // generation.
    std::mt19937 attackRoundingRandom;
    MultiplayerSessionState multiplayer;
    PlayerTimingState timing;
    ClutchSessionState clutch;
    PlayerPresentationState presentation;
};

} // namespace Runtime

