#ifndef TETR_ENGINE_PLACEMENT_APPLICATION_H
#define TETR_ENGINE_PLACEMENT_APPLICATION_H

#include <optional>
#include <vector>

#include "tetr/rules/placement_resolution.h"
#include "tetr/rules/qp_post_lock.h"
#include "tetr/runtime/quick_play_progress.h"
#include "tetr/runtime/runtime_config.h"

namespace Engine {

struct PlacementApplicationState {
    int placedBlocks = 0;
    int totalAttack = 0;
    int totalLines = 0;
    int totalGarbageLines = 0;
    long long score = 0;

    int b2b = 0;
    int combo = 0;

    int difficultClears = 0;
    int b2bExtensions = 0;
    int b2bBreaks = 0;
    int maxB2B = 0;
    int maxCombo = 0;
    int clearMoves = 0;
    int zeroAttackClears = 0;
    int attacksAtLeast4 = 0;
    int attacksAtLeast8 = 0;
    int maxAttack = 0;
    int totalOutgoingAttack = 0;

    bool qpBlighted = false;
    std::optional<Runtime::QuickPlayClearOperation> qpLastOperation;
    std::vector<Runtime::ExtendedAllSpinSignature> qpOperations;
    double qpAltitude = 0.0;
    double qpSpeed = 1.0;
    Runtime::QuickPlayProgress qpProgress;
};

struct PlacementApplicationConfig {
    Runtime::GameMode mode = Runtime::GameMode::Zen;
    bool blitzFlag = false;
    int blitzLevel = 0;

    Runtime::GarbageMode garbageMode = Runtime::GarbageMode::None;
    double garbageMultiple = 1.0;

    Runtime::ModifierMode qpExpert = Runtime::ModifierMode::Disabled;
    Runtime::ModifierMode qpVolatile = Runtime::ModifierMode::Disabled;
    Runtime::ModifierMode qpDoubleHole = Runtime::ModifierMode::Disabled;
    Runtime::AllSpinMode qpAllSpin = Runtime::AllSpinMode::Disabled;
    Runtime::ModifierMode qpBackfire = Runtime::ModifierMode::Disabled;
    Runtime::ModifierMode qpSnakeEyes = Runtime::ModifierMode::Disabled;
    Runtime::QuickPlayConfig qpMods;
    int pieceFamily = 0;
    int pieceColumn = 0;
    bool stackedEdgeI = false;
};

struct PlacementPreOffsetEffects {
    // GarbageMode::Unclear inserts this many ordinary garbage lines before the QP
    // post-lock modifiers are applied. Replay code replays that insertion from
    // the log instead of applying this field directly.
    int directGarbageLines = 0;

    // Snake Eyes reverse inserts these lines before offsetting. Keeping this
    // separate from postOffsetBufferLines is semantically important because
    // this garbage can be cancelled by the current placement.
    int preOffsetBufferLines = 0;

    int attack = 0;
    bool needsOffset = false;
    int offsetAttack = 0;
    int offsetClearTrigger = 0;
    // Multiplayer-only portion of offsetAttack that came from releasing stored
    // B2B charge.  The garbage service sends this portion as three packets.
    int b2bReleaseCharge = 0;
};

struct PlacementApplicationBeginResult {
    PlacementApplicationState state;
    PlacementPreOffsetEffects effects;
    Rules::QPClearOperation qpOperation;
    int clearedGarbageLines = 0;
    bool perfectClear = false;
};

struct PlacementPostOffsetEffects {
    // Full attack generated by the placement, before buffered garbage offset.
    int spikeAttack = 0;
    int outgoingAttack = 0;
    int postOffsetBufferLines = 0;
    int solidGarbageLines = 0;
    bool decayTimedSolidGarbage = false;
};

struct PlacementApplicationResult {
    PlacementApplicationState state;
    PlacementPostOffsetEffects effects;
};

PlacementApplicationBeginResult begin_placement_application(
    const PlacementApplicationState& current,
    const PlacementApplicationConfig& config,
    const Rules::PlacementResult& placement,
    Piece::Type pieceType);

PlacementApplicationResult finish_placement_application(
    const PlacementApplicationBeginResult& begin,
    const PlacementApplicationConfig& config,
    int rawOffsetResult);

} // namespace Engine

#endif
